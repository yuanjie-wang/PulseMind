// ── Bundle the in-frame picker into a committed source string ──
// (PLAN-html-element-edit §设计1, same precedent as the traced brand mark and
// the extension icons: a generator script whose OUTPUT is committed, with a
// test asserting regenerated == committed so the two cannot drift.)
//
//   node scripts/build-preview-picker.mjs
//
// Produces src/main/preview/picker-source.generated.ts exporting
// PICKER_SCRIPT — the IIFE bundle of src/preview-picker/index.ts that
// serve-preview.ts injects into ?pmPreview=1 HTML responses.

import { build } from 'esbuild'
import { writeFileSync, mkdirSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const ENTRY = join(ROOT, 'src/preview-picker/index.ts')
const OUT = join(ROOT, 'src/main/preview/picker-source.generated.ts')

const result = await build({
  entryPoints: [ENTRY],
  bundle: true,
  format: 'iife',
  target: ['chrome120'],
  write: false,
  legalComments: 'none',
  define: { 'process.env.NODE_ENV': '"production"' },
})

const code = result.outputFiles[0].text

// The payload is inlined into a <script> element: a literal `</script` inside
// it would close the host tag early and corrupt every injected page.
if (/<\/script/i.test(code)) {
  console.error('picker bundle contains a literal </script — refusing to generate')
  process.exit(1)
}

const banner =
  '// GENERATED by scripts/build-preview-picker.mjs — do not edit by hand.\n' +
  '// Source: src/preview-picker/index.ts. Regenerate: node scripts/build-preview-picker.mjs\n' +
  "// A committed test asserts this file equals a fresh regeneration.\n"

mkdirSync(dirname(OUT), { recursive: true })
writeFileSync(OUT, `${banner}export const PICKER_SCRIPT = ${JSON.stringify(code)}\n`)

console.log(`picker bundle: ${code.length} bytes → ${OUT}`)
